import { createServer } from "vite";
import { tmpdir } from "node:os";
import { join } from "node:path";
const server = await createServer({ root: process.cwd(), server: { middlewareMode: true }, appType: "custom", logLevel: "error", optimizeDeps: { noDiscovery: true, include: [] } });
const svc = await server.ssrLoadModule("/data/footballService.ts");
const clubs = svc.footballProvider.clubs();
const sizes = clubs.map((c) => svc.playersByClub(c.id).length).sort((a, b) => b - a);
console.log("clubs:", clubs.length, "max:", sizes[0], "min:", sizes[sizes.length-1], "top10:", sizes.slice(0, 10).join(","));
console.log("clubs with >=11:", sizes.filter((s) => s >= 11).length);
await server.close();
